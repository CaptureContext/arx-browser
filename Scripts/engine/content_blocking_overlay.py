def patches():
    yield BACKGROUND, START, ARX_START
    yield BUILD, INPUTS, ARX_INPUTS


def apply(source):
    for relative, before, after in patches():
        replace_once(source / relative, before, after)
    # uBlock's BUILD.gn lists its files at build time, so a new file is enough.
    script = source / SCRIPT
    if not script.exists() or script.read_text() != ARX_SCRIPT:
        script.parent.mkdir(parents=True, exist_ok=True)
        script.write_text(ARX_SCRIPT)
