"""Arx's content blocking on Helium's uBlock Origin component (DEV-884).

Helium compiles uBlock Origin into the framework (`third_party/ublock`) and
loads it into every regular profile. It patched the remote URLs out of uBlock's
list registry (`assets/assets.json`); lists update only through Helium's own
service, which answers a dummy host until Helium's onboarding consent, which Arx
never shows. So in Arx uBlock's lists stayed at their build-time versions and
the cookie notice lists had no source at all.

This overlay adds `js/arx.js` to uBlock and loads it from its background page.

1. Once uBlock is ready, arx.js gives the registry's own entry (`assets.json`)
   upstream uBlock's registry as its remote source when it has none. uBlock
   still starts from the bundled registry, with no network wait, and its own
   updater (37 seconds after launch, then on its usual schedule) replaces the
   registry with upstream's, so lists update from their publishers as in a
   stock uBlock Origin. Helium's two local lists (`helium-annoyances`,
   `helium-unbreak`) aren't in upstream's registry, so uBlock drops them then.
   uBlock also applies upstream's default lists then, which have the cookie
   notice lists off; arx.js keeps the ones that were selected.

   Not an `adminSettings.assetsBootstrapLocation`: Helium keys uBlock's cached
   registry by that location but stores it without it, so uBlock would fetch
   the registry on every start. On a fresh profile that fetch delays uBlock's
   one-time restart (`runtime.reload()` after its first run) into whatever the
   browser is doing by then, which unloads and reloads the extension.
2. It reads `arxContentBlocking` from uBlock's `chrome.storage.local`, which the
   browser writes (`content_blocking_bridge.mm`), at start and on every change:
   `cookieBanners` selects EasyList's and uBlock's cookie notice lists, and
   `trustedSites` (uBlock directives in each site rule's own scope) become
   trusted sites. Each split instance tracks what it applied itself.
   `phishingList` (DEV-923) selects the Phishing URL Blocklist once, next to
   the badware and malware lists uBlock selects by default.
4. Hide Element (DEV-1019): the browser writes `arxElementPicker` = {tabId,
   request} to open uBlock's element picker on a tab (in the instance that has
   the tab), and `arxShowHiddenElement` = {filter, request} to take a filter
   out of My filters and reload the filters. arx.js keeps
   `arxHiddenElements` = {hostname: [filter]} current: My filters' cosmetic
   filters that hide elements on named sites, as the picker writes them, which
   the URL bar's site menu lists.
3. uBlock picks its default lists on its first start in a profile, before the
   browser has written `arxContentBlocking` (that happens when the profile's
   first page opens). arx.js makes Arx's choices part of that pick: the cookie
   notice lists only when the stored setting turns them on, and the Phishing
   URL Blocklist. Applying them later would make uBlock load every list again
   while the first page waits on it (DEV-682's benchmark: one to two seconds
   on a new profile).

If an anchor changes, the build stops.
"""
