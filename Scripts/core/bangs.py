"""Turn Helium's !bang list into the snapshot BrowserCore bundles.

`make bangs` downloads https://services.helium.imput.net/bangs.json, the list
Helium's omnibox would fetch (Kagi Search's bangs plus imput's extras, MIT).
Set BANGS_SOURCE to a local copy to regenerate without the network. The app
never fetches this list; it only reads the generated file.

Each data line is `keywords<TAB>name<TAB>opens-homepage<TAB>template`:
space-separated lowercased keywords, the display name, 1 when an empty query
opens the template's origin, and an HTTP(S) URL with one `{query}`. Lines keep
the source order, which ranks popular bangs first.
"""

import hashlib
import json
import os
import re
import sys
from urllib.parse import quote, urlsplit
from urllib.request import Request, urlopen

from .paths import ROOT

SOURCE_URL = "https://services.helium.imput.net/bangs.json"
OUTPUT = ROOT / "Packages/core/Sources/BrowserCore/Resources/Bangs.tsv"
PLACEHOLDER = "{searchTerms}"
SENTINEL = "ARXBANGQUERY"
# RFC 3986 reserved and unreserved characters plus existing escapes stay as they are.
URL_SAFE = "-._~:/?#[]@!$&'()*+,;=%"
# Kagi's "f" flags: bit 0 opens the base path on an empty query. Absent means every default.
OPEN_BASE_PATH = 1
DEFAULT_FLAGS = 7


def parse(text):
    """Read Helium's JSON with comments and trailing commas, as Chromium's reader allows."""
    header = [line[2:].removeprefix(" ") for line in text.splitlines() if line.startswith("//")]
    body = "\n".join(line for line in text.splitlines() if not line.lstrip().startswith("//"))
    body = re.sub(r",(\s*[\]}])", r"\1", body)
    entries = json.loads(body)
    if not isinstance(entries, list):
        raise ValueError("Helium's bang list is not an array")
    return header, entries


def template(url):
    """Return Arx's `{query}` template, or None when the placeholder is not in a safe position."""
    if not isinstance(url, str) or url.count(PLACEHOLDER) != 1 or SENTINEL in url or "{query}" in url:
        return None
    before, after = url.split(PLACEHOLDER)
    url = quote(before, safe=URL_SAFE) + SENTINEL + quote(after, safe=URL_SAFE)
    parts = urlsplit(url)
    if parts.scheme not in ("http", "https") or not parts.hostname:
        return None
    if SENTINEL in parts.scheme + parts.netloc:
        return None
    if SENTINEL in parts.query:
        # The query is percent-encoded down to unreserved characters, so it is safe in any
        # value, but never in a parameter name.
        field = next(field for field in parts.query.split("&") if SENTINEL in field)
        if "=" not in field or SENTINEL in field.split("=", 1)[0]:
            return None
    return url.replace(SENTINEL, "{query}")


def keyword(trigger):
    if not isinstance(trigger, str):
        return None
    value = trigger.strip().lower()
    if not value or re.search(r"[\s!]", value):
        return None
    return value


def generate(text, provenance=()):
    header, entries = parse(text)
    licence = [line for line in header if not line.startswith(("Generated at", "DO NOT", "Changes belong"))]
    while licence and not licence[0].strip():
        licence.pop(0)
    generated = next((line.split(" ", 2)[2] for line in header if line.startswith("Generated at ")), "unknown")
    if not any("MIT License" in line for line in licence):
        raise ValueError("Helium's bang list no longer carries its MIT licence")

    seen = set()
    lines = []
    skipped = 0
    for entry in entries:
        if not isinstance(entry, dict):
            skipped += 1
            continue
        name = entry.get("s")
        url = template(entry.get("u"))
        keywords = [value for value in map(keyword, entry.get("ts") or []) if value and value not in seen]
        if not isinstance(name, str) or not name.strip() or re.search(r"[\t\r\n]", name) or not url or not keywords:
            skipped += 1
            continue
        seen.update(keywords)
        flags = entry.get("f", DEFAULT_FLAGS)
        opens_homepage = int(isinstance(flags, int) and bool(flags & OPEN_BASE_PATH))
        lines.append("\t".join([" ".join(keywords), name.strip(), str(opens_homepage), url]))

    digest = hashlib.sha256(text.encode()).hexdigest()
    output = [
        "# Helium's !bang list for Arx. Generated by `make bangs` (Scripts/core/bangs.py); do not edit.",
        f"# Source: {SOURCE_URL}",
        f"# Source generated at: {generated}",
        f"# Source SHA-256: {digest}",
        *(f"# {line}" for line in provenance),
        "# Format: keywords<TAB>name<TAB>opens-homepage<TAB>template",
        "#",
        *(f"# {line}".rstrip() for line in licence),
        *lines,
    ]
    return "\n".join(output) + "\n", len(lines), len(seen), skipped


def download():
    request = Request(SOURCE_URL, headers={"Accept": "application/json", "User-Agent": "Arx bang snapshot"})
    with urlopen(request, timeout=30) as response:
        if response.status != 200:
            raise ValueError(f"Helium's bang list answered {response.status}")
        provenance = [f"Source ETag: {response.headers['ETag']}"] if response.headers["ETag"] else []
        return response.read().decode("utf-8"), provenance


def main():
    source = os.environ.get("BANGS_SOURCE")
    if source:
        text, provenance = open(source, encoding="utf-8").read(), []
    else:
        text, provenance = download()
    output, bangs, keywords, skipped = generate(text, provenance)
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(output, encoding="utf-8")
    print(f"{OUTPUT.relative_to(ROOT)}: {bangs} bangs, {keywords} keywords, {skipped} skipped")
    return 0


if __name__ == "__main__":
    sys.exit(main())
